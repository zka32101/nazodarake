/// ステージ番号でグルーピングした一覧を返す。
Map<int, List<Puzzle>> groupPuzzlesByStage() {
  final Map<int, List<Puzzle>> result = {};
  for (final puzzle in allPuzzles) {
    result.putIfAbsent(puzzle.stage, () => []).add(puzzle);
  }
  return result;
}

/// 全ステージ番号の一覧（昇順）。
List<int> get allStageNumbers =>
    allPuzzles.map((p) => p.stage).toSet().toList()..sort();
